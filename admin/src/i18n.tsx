const DICTS: Record<Lang, Dict> = { ru, en };

const pluralRules: Record<Lang, Intl.PluralRules> = { ru: new Intl.PluralRules('ru-RU'), en: new Intl.PluralRules('en-US') };
let currentLang: Lang = 'ru';

/** Russian has three plural forms: 1 монета, 2 монеты, 5 монет. English uses the first two. */
export function plural(n: number, forms: Plural, lang: Lang = currentLang): string {
  const rule = pluralRules[lang].select(n);
  if (rule === 'one') return forms[0];
  if (rule === 'few' || (lang === 'en' && rule === 'other')) return forms[1];
  return forms[2];
}

// --- Numbers and dates, in the hub's time zone ------------------------------------------

let timeZone = 'Asia/Almaty';
export function setTimeZone(zone: string): void {
  timeZone = zone;
}

const MONTHS: Record<Lang, string[]> = {
  ru: ['янв', 'фев', 'мар', 'апр', 'мая', 'июн', 'июл', 'авг', 'сен', 'окт', 'ноя', 'дек'],
  en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
};
const MONTH_NAMES: Record<Lang, string[]> = {
  ru: ['Январь', 'Февраль', 'Март', 'Апрель', 'Май', 'Июнь', 'Июль', 'Август', 'Сентябрь', 'Октябрь', 'Ноябрь', 'Декабрь'],
  en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
};

function zoned(value: string): { y: number; m: number; d: number; h: number; mi: number } | null {
  // A calendar date (YYYY-MM-DD) has no zone; a timestamp is shown in the hub's zone.
  const dateOnly = /^\d{4}-\d{2}-\d{2}$/.test(value);
  const date = new Date(dateOnly ? `${value}T00:00:00Z` : value);
  if (Number.isNaN(date.getTime())) return null;
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone: dateOnly ? 'UTC' : timeZone,
    hourCycle: 'h23',
    year: 'numeric',
    month: 'numeric',
    day: 'numeric',
    hour: 'numeric',
    minute: 'numeric',
  }).formatToParts(date);
  const get = (type: string) => Number(parts.find((p) => p.type === type)?.value);
  return { y: get('year'), m: get('month'), d: get('day'), h: get('hour'), mi: get('minute') };
}

export interface Format {
  num: (n: number | null | undefined) => string;
  pct: (n: number | null | undefined) => string;
  money: (n: number, sign: string) => string;
  day: (iso: string | null | undefined) => string;
  dayYear: (iso: string | null | undefined) => string;
  dayTime: (iso: string | null | undefined) => string;
  month: (yyyyMm: string) => string;
  wait: (iso: string | null | undefined) => string;
  ago: (iso: string | null | undefined) => string;
  coins: (n: number) => string;
  creators: (n: number) => string;
}

function makeFormat(lang: Lang, t: Dict): Format {
  const locale = lang === 'ru' ? 'ru-RU' : 'en-US';
  const numberFormat = new Intl.NumberFormat(locale);
  const decimal = new Intl.NumberFormat(locale, { minimumFractionDigits: 1, maximumFractionDigits: 1 });
  const thisYear = new Date().getFullYear();
  const day = (iso: string | null | undefined, withYear = false): string => {
    if (!iso) return '';
    const p = zoned(iso);
    if (!p) return '';
    const month = MONTHS[lang][p.m - 1];
    const base = lang === 'ru' ? `${p.d} ${month}` : `${p.d} ${month}`;
    return withYear || p.y !== thisYear ? `${base} ${p.y}` : base;
  };
  const num = (n: number | null | undefined): string => (n === null || n === undefined ? '' : numberFormat.format(n));
  return {
    num,
    pct: (n) => (n === null || n === undefined ? '' : `${decimal.format(n)}%`),
    money: (n, sign) => `${numberFormat.format(n)} ${sign}`,
    day: (iso) => day(iso),
    dayYear: (iso) => day(iso, true),
    dayTime: (iso) => {
      const p = iso ? zoned(iso) : null;
      return p ? `${day(iso)}, ${String(p.h).padStart(2, '0')}:${String(p.mi).padStart(2, '0')}` : '';
    },
    month: (yyyyMm) => {
      const [y, m] = yyyyMm.split('-').map(Number) as [number, number];
      return `${MONTH_NAMES[lang][m - 1]} ${y}`;
    },
    wait: (iso) => {
      if (!iso) return '';
      const minutes = Math.max(0, Math.round((Date.now() - Date.parse(iso)) / 60_000));
      if (minutes < 60) return `${minutes} ${t.common.minutes}`;
      const hours = Math.round(minutes / 60);
      if (hours < 48) return `${hours} ${t.common.hours}`;
      return `${Math.round(hours / 24)} ${t.common.days}`;
    },
    ago: (iso) => {
      if (!iso) return t.common.never;
      const p = zoned(iso);
      const today = zoned(new Date().toISOString());
      if (!p || !today) return '';
      const days = Math.round((Date.UTC(today.y, today.m - 1, today.d) - Date.UTC(p.y, p.m - 1, p.d)) / 86_400_000);
      if (days <= 0) return t.common.today;
      if (days === 1) return t.common.yesterday;
      return t.common.daysAgo(days);
    },
    coins: (n) => `${num(n)} ${plural(n, t.common.coins, lang)}`,
    creators: (n) => `${num(n)} ${plural(n, t.common.creators, lang)}`,
  };
}

// --- Context -----------------------------------------------------------------------

interface I18n {
  lang: Lang;
  t: Dict;
  f: Format;
  setLang: (lang: Lang) => void;
}

const STORAGE_KEY = 'ch-admin-lang';

function initialLang(): Lang {
  try {
    return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'ru';
  } catch {
    return 'ru';
  }
}

const I18nContext = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const value = useMemo<I18n>(() => {
    currentLang = lang;
    document.documentElement.lang = lang;
    const t = DICTS[lang];
    return {
      lang,
      t,
      f: makeFormat(lang, t),
      setLang: (next) => {
        try {
          localStorage.setItem(STORAGE_KEY, next);
        } catch {
          /* private mode: the choice lasts for this page only */
        }
        setLangState(next);
      },
    };
  }, [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n outside I18nProvider');
  return value;
}
